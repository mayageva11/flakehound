#!/usr/bin/env node
// Render flakehound.report.json as GitHub-flavored markdown — used for the
// Action's job summary and PR comment. Pure formatting: no analysis here.
import { readFileSync } from 'node:fs';

const reportPath = process.argv[2] ?? 'flakehound.report.json';
const report = JSON.parse(readFileSync(reportPath, 'utf8'));
const { summary, signals, clusters, gate } = report;

const regressions = signals.filter((s) => s.classification === 'regression');
const flaky = [...signals.filter((s) => s.classification === 'flaky')].sort(
  (a, b) => b.flakinessScore - a.flakinessScore,
);
const newClusterIds = new Set(gate.newClusters ?? []);
const failing = gate.newRegressions.length > 0;

const strip = (history = []) =>
  history.map((h) => (h.verdict === 'pass' ? '✅' : h.verdict === 'fail' ? '❌' : '⬜')).join('');

const lines = [];
lines.push('<!-- flakehound-report -->');
lines.push(`## 🐕 flakehound — ${failing ? `❌ ${gate.newRegressions.length} new regression(s)` : '✅ no new regressions'}`);
lines.push('');
lines.push(
  `${summary.testRuns} test runs · ${summary.testsAnalyzed} tests analyzed · gate: ${gate.newRegressions.length} new / ${gate.knownRegressions.length} known / ${gate.resolvedRegressions.length} resolved${gate.baselineUsed ? '' : ' · no baseline (fail-safe)'}`,
);

if (regressions.length > 0) {
  lines.push('', '### Regressions', '');
  lines.push('| test | broken since | runs |', '|---|---|---|');
  for (const s of regressions) {
    lines.push(`| \`${s.testId}\` | \`${s.brokenSinceSha ?? '?'}\` | ${strip(s.history)} |`);
  }
}

if (flaky.length > 0) {
  lines.push('', '### Flaky — quarantine candidates', '');
  lines.push('| test | score | confidence | runs |', '|---|---|---|---|');
  for (const s of flaky) {
    lines.push(`| \`${s.testId}\` | ${s.flakinessScore.toFixed(2)} | ${s.confidence} | ${strip(s.history)} |`);
  }
}

if (clusters.length > 0) {
  const ranked = [...clusters].sort(
    (a, b) =>
      b.occurrences * b.tests.length - a.occurrences * a.tests.length ||
      a.representativeTrace.localeCompare(b.representativeTrace),
  );
  lines.push('', `### Failure clusters (${clusters.length})`, '');
  for (const c of ranked.slice(0, 5)) {
    const badge = gate.baselineUsed && newClusterIds.has(c.id) ? ' **🆕 NEW**' : '';
    const head = c.representativeTrace.split(' at ')[0].trim().slice(0, 120);
    lines.push(`- \`${c.id}\`${badge} — ${c.occurrences}× across ${c.tests.length} test(s): ${head}`);
    if (c.hypothesis) lines.push(`  - 🤖 *${c.hypothesis.category}* — ${c.hypothesis.explanation}`);
  }
}

lines.push('', `<sub>exit code ${failing ? 1 : 0} · generated by <a href="https://github.com/mayageva11/flakehound">flakehound</a></sub>`);
process.stdout.write(lines.join('\n') + '\n');
